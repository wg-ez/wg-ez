//! Build script : verifie l'artefact CSS et pre-gzippe les assets statiques.
//!
//! - Echec si `static/css/app.css` manque (artefact commite produit par le stage
//!   `css` du Dockerfile (`docker/Dockerfile`), `docker build -f docker/Dockerfile --target css .`,
//!   seule dep npm ; le binaire Rust ne touche jamais a Node).
//! - Tout fichier de `static/` de plus de 1024 octets est gzippe vers `$OUT_DIR`.
//! - Un manifeste est genere avec des `include_bytes!` pour servir le gzip pre-calcule.
//!
//! Vitesse UI : au runtime `static/` est servi depuis le filesystem
//! (`static_file` lit `./static/`), le gzip embarque n'est qu'un best-effort.
//! Le script ne surveille donc que lui-meme et `app.css` (garde-fou) : editer
//! `app.js`/vendor ne redeclenche ni le script ni le re-link LTO (le build
//! Docker frais re-gzippe tout de toute facon).

use std::env;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

use flate2::Compression;
use flate2::write::GzEncoder;

const CSS_ARTIFACT: &str = "static/css/app.css";
const SIZE_THRESHOLD: u64 = 1024;

fn fail(msg: &str) -> ! {
    eprintln!("build script error: {msg}");
    std::process::exit(1);
}

fn collect_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), String> {
    let entries =
        fs::read_dir(dir).map_err(|e| format!("cannot read dir {}: {e}", dir.display()))?;
    for entry in entries {
        let entry = entry.map_err(|e| format!("cannot read entry in {}: {e}", dir.display()))?;
        let path = entry.path();
        let kind = entry
            .file_type()
            .map_err(|e| format!("cannot stat {}: {e}", path.display()))?;
        if kind.is_dir() {
            collect_files(&path, out)?;
        } else if kind.is_file() {
            out.push(path);
        }
    }
    Ok(())
}

fn flat_name(rel: &Path) -> String {
    rel.to_string_lossy().replace(['/', '\\'], "__")
}

fn main() {
    let manifest_dir = match env::var("CARGO_MANIFEST_DIR") {
        Ok(v) => PathBuf::from(v),
        Err(_) => PathBuf::from("."),
    };
    let static_dir = manifest_dir.join("static");
    let css = manifest_dir.join(CSS_ARTIFACT);

    if !css.is_file() {
        fail(
            "static/css/app.css is missing; generate it with `docker build -f docker/Dockerfile --target css .` (tailwind via @tailwindcss/cli) before building",
        );
    }

    let out_dir = match env::var("OUT_DIR") {
        Ok(v) => PathBuf::from(v),
        Err(_) => PathBuf::from("target/build-out"),
    };
    let gz_dir = out_dir.join("static-gz");

    match fs::create_dir_all(&gz_dir) {
        Ok(()) => {}
        Err(e) => fail(&format!("cannot create {}: {e}", gz_dir.display())),
    }

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=static/css/app.css");

    let mut files: Vec<PathBuf> = Vec::new();
    match collect_files(&static_dir, &mut files) {
        Ok(()) => {}
        Err(e) => fail(&e),
    }
    files.sort();

    let mut manifest = String::from(
        "// @generated by build.rs : assets statiques pre-gzippes.\n\
         pub struct PrecompressedAsset {\n    pub path: &'static str,\n    pub data: &'static [u8],\n}\n\
         pub static PRECOMPRESSED_ASSETS: &[PrecompressedAsset] = &[\n",
    );

    for path in &files {
        let meta = match fs::metadata(path) {
            Ok(m) => m,
            Err(e) => fail(&format!("cannot stat {}: {e}", path.display())),
        };
        if meta.len() <= SIZE_THRESHOLD {
            continue;
        }
        let rel = match path.strip_prefix(&static_dir) {
            Ok(r) => r.to_path_buf(),
            Err(e) => fail(&format!("cannot relativize {}: {e}", path.display())),
        };
        let bytes = match fs::read(path) {
            Ok(b) => b,
            Err(e) => fail(&format!("cannot read {}: {e}", path.display())),
        };
        // `default()` (niveau 6) plutot que `best()` (niveau 9) : ~5x plus
        // rapide a encoder pour ~1 % de taille en plus sur ~80 Ko.
        let mut enc = GzEncoder::new(Vec::new(), Compression::default());
        match enc.write_all(&bytes) {
            Ok(()) => {}
            Err(e) => fail(&format!("cannot gzip {}: {e}", path.display())),
        }
        let gz = match enc.finish() {
            Ok(g) => g,
            Err(e) => fail(&format!("cannot finish gzip {}: {e}", path.display())),
        };
        let name = flat_name(&rel) + ".gz";
        let dest = gz_dir.join(&name);
        match fs::write(&dest, &gz) {
            Ok(()) => {}
            Err(e) => fail(&format!("cannot write {}: {e}", dest.display())),
        }
        let logical = rel.to_string_lossy().replace('\\', "/");
        manifest.push_str(&format!(
            "    PrecompressedAsset {{ path: \"{logical}\", data: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/static-gz/{name}\")) }},\n"
        ));
    }
    manifest.push_str("];\n");

    let manifest_path = out_dir.join("static_precompressed.rs");
    match fs::write(&manifest_path, manifest.as_bytes()) {
        Ok(()) => {}
        Err(e) => fail(&format!("cannot write {}: {e}", manifest_path.display())),
    }
}
